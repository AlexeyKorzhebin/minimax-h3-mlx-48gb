# -- run_song: full orchestration with every subprocess faked ---------------------------------


def _wire_full_fake_pipeline(track_dir: Path, *, whisper_segments, whisper_text="",
                              audio_dur="90.0"):
    fake = _FakeRun()

    def handle_generate(cmd):
        out_path = Path(cmd[cmd.index("--output") + 1])
        out_path.write_bytes(b"fake raw wav")
        return _Result(stdout=f"[audio] {out_path}  shape=(1,2)  sr=44100  dur={audio_dur}s\n")

    def handle_ffmpeg(cmd):
        # the output path is always the last argv element for both master() and to_mp3()
        Path(cmd[-1]).write_bytes(b"fake ffmpeg output")
        return _Result()

    def handle_whisper(cmd):
        out_dir = Path(cmd[cmd.index("--output-dir") + 1])
        name = cmd[cmd.index("--output-name") + 1]
        payload = {"text": whisper_text, "segments": whisper_segments}
        (out_dir / f"{name}.json").write_text(json.dumps(payload), encoding="utf-8")
        return _Result()

    fake.add(_is_generate_call, handle_generate)
    fake.add(_is_ffmpeg_call, handle_ffmpeg)
    fake.add(_is_mlx_whisper_call, handle_whisper)
    return fake


def test_run_song_wires_all_four_steps_into_a_song_result(tmp_path):
    track_dir = tmp_path / "track"
    segments = [{"start": 0.0, "end": 3.0, "text": "spi moy malenkiy"}]
    fake = _wire_full_fake_pipeline(track_dir, whisper_segments=segments,
                                     whisper_text="spi moy malenkiy", audio_dur="87.5")

    result = sr.run_song(
        track_dir, lyrics="[intro]\nspi moy malenkiy", caption="a lullaby", duration=90.0,
        seed=7, music3_python="fake-python3", model_dir="fake-model-dir", run=fake)

    assert isinstance(result, sr.SongResult)
    assert result.wav == track_dir / "song.wav"
    assert result.mastered_wav == track_dir / "song.mastered.wav"
    assert result.mp3 == track_dir / "song.mp3"
    assert result.mastered_mp3 == track_dir / "song.mastered.mp3"
    for path in (result.wav, result.mastered_wav, result.mp3, result.mastered_mp3):
        assert path.is_file()
    assert result.duration == pytest.approx(87.5)
    assert result.transcript == "spi moy malenkiy"
    assert result.sections == [{"name": "intro", "start": 0.0, "end": 87.5}]
    assert result.undersung is False

    # Whisper transcribed the *mastered* wav, not the raw take.
    whisper_call = next(c for c in fake.calls if Path(c[0]).name == "mlx_whisper")
    assert whisper_call[-1] == str(track_dir / "song.mastered.wav")


