"""One song job end to end: generation, mastering, mp3, Whisper sung-lyrics check.

**Music3 is never actually run here** -- it needs the GPU, and the GPU may be busy with something
else entirely (H3 and Music3 do not coexist, design spec, "Трек"). Every `run_song`/`_generate_wav`/
`_transcribe` test substitutes a fake `run` callable in place of `subprocess.run`, mirroring
`test_worker.py`'s `spawn` substitution for the same reason. The one exception is `master`/`to_mp3`
(the ffmpeg mastering chain): those *are* exercised against a real `ffmpeg`, fed a synthetic sine
wave generated by `ffmpeg -f lavfi` -- no GPU, no external model, just the mastering chain itself.

The Whisper fuzzy-matching tests (`check_lyrics_sung` and friends) are pure functions -- no
subprocess at all -- and are built directly from the 2026-08-18 "Колыбельная" run's real facts: a
268 s take against a 295 s cap that was *not* undersung (Music3 simply ran out of lyrics), a real
Whisper mishearing ("в висках" -> "песка"), and an undersung take that looks like a sung head and
an unsung tail, not a short recording.
"""
