# -- check_lyrics_sung: fuzzy line/segment matching ----------------------------------------------


def _seg(start, end, text):
    return {"start": start, "end": end, "text": text}


def test_a_fully_sung_short_song_is_not_undersung_and_every_section_gets_a_start():
    lyrics = "[intro]\nСпи мой маленький\n\n[chorus]\nСпи мой князь мой белый сокол"
    segments = [
        _seg(0.0, 3.0, "Спи мой маленький"),
        _seg(3.0, 7.0, "Спи мой князь мой белый сокол"),
    ]
    sections, undersung = sr.check_lyrics_sung(lyrics, segments, duration=7.0)
    assert undersung is False
    assert sections == [
        {"name": "intro", "start": 0.0, "end": 3.0},
        {"name": "chorus", "start": 3.0, "end": 7.0},
    ]


def test_whisper_mishearing_v_viskah_to_peska_still_matches_at_50_percent_overlap():
    """The real 2026-08-18 example: Whisper heard "Имя древнее песка" for the sung line "Имя
    древнее в висках". 2 of the line's 4 words survive -- exactly the 50% floor
    `LINE_MATCH_THRESHOLD` is pinned to. This must match, or a correctly-sung chorus line would be
    wrongly counted against the undersung gate.
    """
    line_words = sr._word_set("Имя древнее в висках")
    heard_words = sr._word_set("Имя древнее песка")
    assert sr._overlap(line_words, heard_words) == pytest.approx(0.5)
    assert sr._overlap(line_words, heard_words) >= sr.LINE_MATCH_THRESHOLD


def test_check_lyrics_sung_matches_the_mishearing_end_to_end():
    lyrics = "[chorus]\nИмя древнее в висках"
    segments = [_seg(10.0, 13.0, "Имя древнее песка")]
    sections, undersung = sr.check_lyrics_sung(lyrics, segments, duration=13.0)
    assert sections == [{"name": "chorus", "start": 10.0, "end": 13.0}]
    assert undersung is False


def test_268_of_295_seconds_with_a_fully_sung_tail_is_not_undersung():
    """Music3 stopping early once the lyrics run out (268s audio, 295s cap) is not undersung by
    itself -- what matters is whether the *lyrics'* tail was sung, which this fixture makes true.
    """
    lyrics = "\n".join([
        "[verse]",
        "line one",
        "line two",
        "line three",
        "[outro]",
        "line four",
        "line five",
        "line six",
    ])
    segments = [
        _seg(0.0, 10.0, "line one"),
        _seg(10.0, 20.0, "line two"),
        _seg(20.0, 30.0, "line three"),
        _seg(30.0, 40.0, "line four"),
        _seg(40.0, 50.0, "line five"),
        _seg(50.0, 60.0, "line six"),
    ]
    sections, undersung = sr.check_lyrics_sung(lyrics, segments, duration=268.0)
    assert undersung is False
    assert sections[-1]["end"] == 268.0


def test_undersung_take_has_a_sung_head_and_an_unsung_tail():
    """Shape lifted from the real "Колыбельная" undersung diagnosis: the bridge sings fine, then
    the final chorus/outro go completely unmatched while the audio (per the design spec) keeps
    playing as instrumental. Every line uses its own distinct vocabulary -- no shared filler word
    across lines -- so a line cannot spuriously clear the 50% overlap floor against an unrelated
    already-matched segment merely by sharing one common word with it.
    """
    lyrics = "\n".join([
        "[bridge]", "альдред здесь иди милый", "поцелуй меня чело",
        "[verse]", "закрою двери клинок", "король оставил веру",
        "[chorus]", "спи мой белый сокол", "имя древнее столетья",
        "[outro]", "спи мой светлый князь", "мать твоя стража",
    ])
    segments = [
        _seg(0.0, 5.0, "альдред здесь иди милый"),
        _seg(5.0, 10.0, "поцелуй меня чело"),
        _seg(10.0, 15.0, "закрою двери клинок"),
        _seg(15.0, 20.0, "король оставил веру"),
        # final chorus and outro: not sung -- only a trailing hallucinated segment with no
        # relation to the lyrics at all (e.g. a fade-out caption-credit artifact).
        _seg(20.0, 24.0, "субтитры делал дима торжок"),
    ]
    sections, undersung = sr.check_lyrics_sung(lyrics, segments, duration=24.0)
    assert undersung is True
    by_name = {s["name"]: s for s in sections}
    assert by_name["bridge"]["start"] == 0.0
    assert by_name["verse"]["start"] == 10.0
    assert by_name["chorus"]["start"] is None
    assert by_name["outro"]["start"] is None


def test_a_hallucinated_tail_segment_with_no_match_is_simply_ignored():
    lyrics = "[outro]\nSpi moy svetlyy"
    segments = [
        _seg(0.0, 2.0, "Spi moy svetlyy"),
        _seg(2.0, 6.0, "субтитры делал дима торжок"),
    ]
    sections, undersung = sr.check_lyrics_sung(lyrics, segments, duration=6.0)
    assert undersung is False
    assert sections == [{"name": "outro", "start": 0.0, "end": 6.0}]


def test_a_repeated_section_name_gets_two_separate_entries_matched_in_order():
    lyrics = "\n".join([
        "[chorus]", "spi moy knyaz",
        "[verse]", "middle line",
        "[chorus]", "spi moy knyaz",
    ])
    segments = [
        _seg(0.0, 3.0, "spi moy knyaz"),
        _seg(3.0, 6.0, "middle line"),
        _seg(6.0, 9.0, "spi moy knyaz"),
    ]
    sections, undersung = sr.check_lyrics_sung(lyrics, segments, duration=9.0)
    assert len(sections) == 3
    assert [s["name"] for s in sections] == ["chorus", "verse", "chorus"]
    assert sections[0]["start"] == 0.0
    assert sections[2]["start"] == 6.0, "second chorus must not match the first chorus's segment"


def test_undersung_threshold_is_exactly_60_percent_of_the_last_third():
    # 9 lines -> last third is lines[6:], 3 lines. 2/3 matched = 66.7% -> not undersung.
    lyrics = "\n".join(f"line{i}" for i in range(9))
    segments = [_seg(float(i), float(i) + 1, f"line{i}") for i in range(9) if i not in (7,)]
    _, undersung = sr.check_lyrics_sung(lyrics, segments)
    assert undersung is False

    # Drop one more of the last three matches (now 1/3 = 33%) -> undersung.
    segments_worse = [_seg(float(i), float(i) + 1, f"line{i}") for i in range(9) if i not in (7, 8)]
    _, undersung_worse = sr.check_lyrics_sung(lyrics, segments_worse)
    assert undersung_worse is True


def test_check_lyrics_sung_on_empty_lyrics_is_not_undersung():
    sections, undersung = sr.check_lyrics_sung("", [])
    assert sections == []
    assert undersung is False


# -- master / to_mp3: the one real-ffmpeg test -----------------------------------------------


def _make_sine_wav(path: Path, duration: float = 2.0) -> None:
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi",
           "-i", f"sine=frequency=440:duration={duration}", str(path)]
    subprocess.run(cmd, check=True, capture_output=True)


def _ffprobe_duration(path: Path) -> float:
    cmd = ["ffprobe", "-v", "error", "-show_entries", "format=duration",
           "-of", "default=noprint_wrappers=1:nokey=1", str(path)]
    result = subprocess.run(cmd, check=True, capture_output=True, text=True)
    return float(result.stdout.strip())


def test_master_and_to_mp3_run_a_real_ffmpeg_on_a_synthetic_sine(tmp_path):
    wav = tmp_path / "sine.wav"
    _make_sine_wav(wav, duration=2.0)

    mastered = sr.master(wav, tmp_path / "sine.mastered.wav")
    assert mastered == tmp_path / "sine.mastered.wav"
    assert mastered.is_file()
    assert mastered.stat().st_size > 0
    assert _ffprobe_duration(mastered) == pytest.approx(2.0, abs=0.2)

    mp3 = sr.to_mp3(wav, tmp_path / "sine.mp3")
    mastered_mp3 = sr.to_mp3(mastered, tmp_path / "sine.mastered.mp3")
    for out in (mp3, mastered_mp3):
        assert out.is_file()
        assert out.stat().st_size > 0
        assert _ffprobe_duration(out) == pytest.approx(2.0, abs=0.3)


