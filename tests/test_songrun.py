# -- fake subprocess plumbing: _generate_wav / _transcribe / run_song -------------------------


class _FakeRun:
    """Stands in for `subprocess.run`: records every call and, per call, either runs a canned
    side effect (writing whatever file a real subprocess would have written) or just returns a
    canned `CompletedProcess`-shaped result. Matches by the second argv element (the script/binary
    name), the same way a human would recognize which of `run_song`'s four subprocess calls just
    ran.
    """

    def __init__(self):
        self.calls: list[list[str]] = []
        self.handlers = {}

    def add(self, matcher, handler):
        self.handlers[matcher] = handler

    def __call__(self, cmd, **kwargs):
        self.calls.append(cmd)
        for matcher, handler in self.handlers.items():
            if matcher(cmd):
                return handler(cmd)
        raise AssertionError(f"no fake handler matched {cmd}")


class _Result:
    def __init__(self, returncode=0, stdout="", stderr=""):
        self.returncode = returncode
        self.stdout = stdout
        self.stderr = stderr


def _is_generate_call(cmd):
    return cmd[1] == str(sr.MUSIC3_GENERATE_SCRIPT)


def _is_mlx_whisper_call(cmd):
    return Path(cmd[0]).name == "mlx_whisper"


def _is_ffmpeg_call(cmd):
    return cmd[0] == "ffmpeg"


def test_generate_wav_parses_the_actual_duration_from_stdout(tmp_path):
    fake = _FakeRun()

    def handle_generate(cmd):
        out_path = Path(cmd[cmd.index("--output") + 1])
        out_path.write_bytes(b"fake wav bytes")
        stdout = ("[timing] model load: 3.5 s\n"
                  "[audio] " + str(out_path) + "  shape=(100, 2)  sr=44100  dur=268.3s\n")
        return _Result(returncode=0, stdout=stdout)

    fake.add(_is_generate_call, handle_generate)

    wav_path, duration = sr._generate_wav(
        "python3", "modeldir", "caption text", "lyrics text", 295.0, 30, 7, tmp_path, run=fake)

    assert wav_path == tmp_path / "song.wav"
    assert wav_path.is_file()
    assert duration == pytest.approx(268.3)
    assert (tmp_path / "caption.txt").read_text(encoding="utf-8") == "caption text"
    assert (tmp_path / "lyrics.txt").read_text(encoding="utf-8") == "lyrics text"
    assert "dur=268.3s" in (tmp_path / "gen.log").read_text(encoding="utf-8")

    [cmd] = fake.calls
    assert cmd[0] == "python3"
    assert "--duration" in cmd and cmd[cmd.index("--duration") + 1] == "295.0"
    assert "--seed" in cmd and cmd[cmd.index("--seed") + 1] == "7"


